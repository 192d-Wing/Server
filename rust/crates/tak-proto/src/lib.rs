/// Default upper bound, in bytes, for one encoded `TakMessage` and for the
/// payload of one stream frame (plan section 3.4).
///
/// The reference accepts any length (DEV-01c); TAK-RS bounds it so a peer
/// cannot make the server buffer an arbitrary amount for a single message.
pub const MAX_MESSAGE_BYTES_DEFAULT: usize = 8 * 1024 * 1024;

/// Decodes one `TakMessage`, rejecting `buf` before decoding when it is longer
/// than `max_len` bytes.
///
/// Decoding follows prost: proto3 strings must be valid UTF-8 (K-26), unknown
/// fields are skipped and not kept (K-25), nesting is limited to prost's
/// recursion limit of 100, and a known field sent with the wrong wire type
/// rejects the message (DEV-04; the reference ignores such a field).
///
/// # Errors
///
/// [`DecodeError::TooLarge`] when `buf.len() > max_len`;
/// [`DecodeError::Malformed`] when the bytes are not a valid `TakMessage`.
//
// COMPLIANCE MAPPING:
// - NIST 800-53: SI-10 (Information Input Validation), SC-5 (Denial-of-service
//   Protection)
// PARITY: src/takserver-core/src/main/java/com/bbn/marti/nio/protocol/connections/StreamingProtoBufProtocol.java#onDataReceived
pub fn decode_tak_message(buf: &[u8], max_len: usize) -> Result<v1::TakMessage, DecodeError> {
    if buf.len() > max_len {
        return Err(DecodeError::TooLarge {
            len: buf.len(),
            max: max_len,
        });
    }
    v1::TakMessage::decode(buf).map_err(DecodeError::Malformed)
}

/// Encodes a `TakMessage` to the bytes the reference server writes for it.
///
/// Fields are written in tag order and proto3 defaults are omitted, as
/// protobuf-java does (plan section 1.7, K-24). Whether a `-0.0` double must
/// be written is fixed by the golden corpus (C-08); this function is the one
/// place that changes if it must.
#[must_use]
pub fn encode_tak_message(msg: &v1::TakMessage) -> Vec<u8> {
    msg.encode_to_vec()
}

/// Why a `TakMessage` could not be decoded.
///
/// `Display` never includes message bytes (SI-11); the wrapped prost error
/// names only the message and field where decoding stopped.
#[derive(Clone, Debug, PartialEq, Eq, thiserror::Error)]
#[non_exhaustive]
pub enum DecodeError {
    /// The input is longer than the caller's limit; it was not decoded.
    #[error("protobuf message of {len} bytes exceeds the limit of {max} bytes")]
    TooLarge {
        /// Input length in bytes.
        len: usize,
        /// The limit that was exceeded.
        max: usize,
    },
    /// The input is not a valid encoding of the message.
    #[error("malformed protobuf message")]
    Malformed(#[source] prost::DecodeError),
}

impl DecodeError {
    /// The error category, for metrics and audit records.
    #[must_use]
    pub fn kind(&self) -> DecodeErrorKind {
        match self {
            Self::TooLarge { .. } => DecodeErrorKind::TooLarge,
            Self::Malformed(_) => DecodeErrorKind::Malformed,
        }
    }
}

/// Category of a [`DecodeError`], with a stable code.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
#[non_exhaustive]
pub enum DecodeErrorKind {
    /// See [`DecodeError::TooLarge`].
    TooLarge,
    /// See [`DecodeError::Malformed`].
    Malformed,
}

impl DecodeErrorKind {
    /// Stable code for metrics and audit records (e.g. `"proto.too_large"`).
    #[must_use]
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::TooLarge => "proto.too_large",
            Self::Malformed => "proto.malformed",
        }
    }
}
