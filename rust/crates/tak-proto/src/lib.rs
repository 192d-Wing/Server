//! TAK Protocol v1 message types and their bounded wire handling.
//!
//! The message types are generated at build time from the reference `.proto`
//! schemas, read in place from `src/takserver-protobuf` (see `build.rs`). They
//! are exposed by protobuf package:
//!
//! - [`v1`]: `atakmap.commoncommo.protobuf.v1` (`TakMessage`, `CotEvent`,
//!   `Detail` and its typed sub-messages, `TakControl`, `Message`,
//!   `MissionAnnouncement`);
//! - [`cop`]: `gov.tak.cop.proto.v1` (`BinaryPayload`);
//! - [`atakmap`]: `com.atakmap` (federation `fig.proto` and
//!   `streaminginput.proto` messages; message types only, no gRPC services).
//!
//! [`decode_tak_message`] rejects oversized input before decoding, and
//! [`framing`] implements the stream and mesh (UDP) frames as pure functions.
//! Nothing here performs I/O, holds state, or calls cryptography; the crate
//! builds for `wasm32-unknown-unknown`.
//
// COMPLIANCE MAPPING:
// - NIST 800-53: SI-10 (Information Input Validation), SC-5 (Denial-of-service
//   Protection)
// - ASD STIG: APSC-DV-002530 / V-222606, APSC-DV-002590 / V-222612
//   (unverified)

